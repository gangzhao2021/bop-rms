import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdtemp, readdir, readFile, rm } from "node:fs/promises";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { URL } from "node:url";
import pg from "pg";
import { it } from "vitest";
import {
  createLocalFilesystemMediaImageObjectStore,
  createProductImageService,
  loadProductImages,
  MediaProductImageError,
} from "../../bop/media/src/index.ts";
import { renderPilotAclSql } from "../../../tooling/environment/pilot-acl-render.mjs";
import { withIsolatedDatabase } from "../test-support/isolated-database.mjs";

const { Client } = pg;
// Test image generator only: sharp is a dependency of @bop/media, not of this package.
const sharp = createRequire(new URL("../../bop/media/package.json", import.meta.url))("sharp");
const id = (n) => "0190fa38-0000-7000-8000-" + n.toString(16).padStart(12, "0");

/**
 * WP-2423 menu descriptions and photos: Media records processed product photos in the
 * append-only, Brand-scoped bop_media.product_image (migration 2000_079) after writing the six
 * renditions through the pilot local-filesystem object store. Persistence runs as a restricted
 * NOBYPASSRLS role holding exactly the rendered pilot API grants (matrix + Owner-approved
 * additions); only role creation and owner assertions use the owner client. Test images are
 * synthetic (generated by sharp).
 */
it("records product photos once per reference, keeps them Brand scoped and append-only, and stores six renditions", async () => {
  await withIsolatedDatabase({ caseId: "wp2423_photo" }, async (context) => {
    const admin = new Client(context.clientConfig);
    await admin.connect();
    const api = "wp2423_photo_" + context.runId,
      worker = "wp2423_photo_w_" + context.runId;
    const directory = join(await mkdtemp(join(tmpdir(), "bop-photo-")), "media", "product-images");
    try {
      for (const name of [api, worker])
        await admin.query(
          "CREATE ROLE " + name + " NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE",
        );
      const root = new URL("../../../docs/spec/", import.meta.url);
      const matrices = await Promise.all(
        ["pilot-acl-matrix.json", "pilot-acl-additions.json"].map(async (file) =>
          JSON.parse(await readFile(new URL(file, root), "utf8")),
        ),
      );
      await admin.query(renderPilotAclSql(matrices, { api, worker }));
      const tenant = id(1),
        brand = id(2),
        otherBrand = id(3),
        store = id(4),
        product = id(5),
        otherProduct = id(6),
        actor = id(7);

      /** One restricted-role transaction (pilot API grants); the store sets its own scope. */
      const run = async (work) => {
        const client = new Client(context.clientConfig);
        await client.connect();
        try {
          await client.query("BEGIN");
          await client.query("SET LOCAL ROLE " + api);
          await client.query("SELECT set_config('bop.tenant_id',$1,true)", [tenant]);
          const result = await work({
            query: (sql, values) => client.query(sql, values === undefined ? [] : [...values]),
          });
          await client.query("COMMIT");
          return result;
        } catch (error) {
          await client.query("ROLLBACK").catch(() => undefined);
          throw error;
        } finally {
          await client.end();
        }
      };
      const service = createProductImageService({
        objectStore: createLocalFilesystemMediaImageObjectStore({ directory }),
      });
      const photo = await sharp({
        create: { width: 800, height: 600, channels: 3, background: { r: 200, g: 120, b: 60 } },
      })
        .jpeg()
        .withExif({ IFD3: { GPSLatitudeRef: "N", GPSLatitude: "43/1 39/1 0/1" } })
        .toBuffer();
      const input = (imageReference, brandReference, productReference = product) => ({
        imageReference,
        tenantReference: tenant,
        brandReference,
        productReference,
        actorReference: actor,
        declaredContentType: "image/jpeg",
        bytes: photo,
        createdAt: "2026-10-17T12:00:00.000Z",
      });

      // Ingest: six content-addressed files, then one row.
      const record = await run((tx) => service.ingest(tx, input(id(10), brand)));
      assert.equal(record.renditions.length, 6);
      assert.deepEqual([record.width, record.height], [1280, 960]);
      const files = (await readdir(directory)).sort();
      assert.deepEqual(files, record.renditions.map((r) => r.path.split("/").at(-1)).sort());
      for (const file of files) {
        const bytes = await readFile(join(directory, file));
        assert.equal(createHash("sha256").update(bytes).digest("hex"), file.slice(0, 64));
        assert.equal((await sharp(bytes).metadata()).exif, undefined);
      }
      const count = async () =>
        Number((await admin.query("SELECT count(*) FROM bop_media.product_image")).rows[0].count);
      assert.equal(await count(), 1);
      const stored = (await admin.query("SELECT * FROM bop_media.product_image")).rows[0];
      assert.equal(stored.storage_profile, "PilotLocalFilesystemV1");
      assert.equal(stored.data_classification, "Public");
      assert.equal(stored.source_byte_size, photo.byteLength);
      assert.ok(!("source_checksum" in stored));

      // Idempotent: the same reference returns the recorded image; reuse for another product is refused.
      assert.deepEqual(await run((tx) => service.ingest(tx, input(id(10), brand))), record);
      assert.equal(await count(), 1);
      await assert.rejects(
        run((tx) => service.ingest(tx, input(id(10), brand, otherProduct))),
        (error) =>
          error instanceof MediaProductImageError && error.code === "MEDIA_IMAGE_NOT_FOUND",
      );

      // Brand scope: another Brand's image is invisible; prepare + record path for that Brand.
      const prepared = await service.prepare({ declaredContentType: "image/jpeg", bytes: photo });
      const otherRecord = await run((tx) =>
        service.record(tx, {
          imageReference: id(11),
          tenantReference: tenant,
          brandReference: otherBrand,
          productReference: id(12),
          actorReference: actor,
          createdAt: "2026-10-17T12:01:00.000Z",
          prepared,
        }),
      );
      const brandImages = await run((tx) =>
        loadProductImages(tx, { brandReference: brand, imageReferences: [id(10), id(11)] }),
      );
      assert.deepEqual([...brandImages.keys()], [id(10)]);
      assert.deepEqual(brandImages.get(id(10)), record);
      const otherImages = await run((tx) =>
        service.load(tx, { brandReference: otherBrand, imageReferences: [id(10), id(11)] }),
      );
      assert.deepEqual([...otherImages.entries()], [[id(11), otherRecord]]);
      // A Brand cannot take a reference already recorded by another Brand.
      await assert.rejects(
        run((tx) => service.ingest(tx, input(id(11), brand))),
        (error) =>
          error instanceof MediaProductImageError &&
          error.code === "MEDIA_IMAGE_STORAGE_UNAVAILABLE",
      );

      // RLS: a different Brand scope, or any Store scope, cannot insert or read.
      const rawInsert = (scopeBrand, scopeStore, rowBrand, imageId) =>
        run(async (tx) => {
          await tx.query(
            "SELECT set_config('bop.brand_id',$1,true),set_config('bop.store_id',$2,true)",
            [scopeBrand, scopeStore],
          );
          return tx.query(
            `INSERT INTO bop_media.product_image(image_id,tenant_id,brand_id,product_id,storage_profile,
               source_content_type,source_byte_size,width,height,renditions_json,data_classification,
               created_by_actor_id,created_at)
             SELECT $1,tenant_id,$2,product_id,storage_profile,source_content_type,source_byte_size,
               width,height,renditions_json,data_classification,created_by_actor_id,created_at
             FROM (VALUES($3::uuid,$4::uuid,'PilotLocalFilesystemV1','image/jpeg',100,1280,960,$5::jsonb,
               'Public',$6::uuid,'2026-10-17T12:00:00.000Z'::timestamptz))
               v(tenant_id,product_id,storage_profile,source_content_type,source_byte_size,width,height,
                 renditions_json,data_classification,created_by_actor_id,created_at)`,
            [imageId, rowBrand, tenant, product, JSON.stringify(record.renditions), actor],
          );
        });
      const rlsDenied = (error) => error?.code === "42501";
      await assert.rejects(rawInsert(otherBrand, "", brand, id(20)), rlsDenied);
      await assert.rejects(rawInsert(brand, store, brand, id(21)), rlsDenied);
      assert.equal((await rawInsert(brand, "", brand, id(22))).rowCount, 1);
      const storeScoped = await run(async (tx) => {
        await tx.query(
          "SELECT set_config('bop.brand_id',$1,true),set_config('bop.store_id',$2,true)",
          [brand, store],
        );
        return tx.query("SELECT count(*) FROM bop_media.product_image", []);
      });
      assert.equal(storeScoped.rows[0].count, "0");
      assert.equal(await count(), 3);

      // Append-only: UPDATE and DELETE are no-ops for the API role and the owner.
      const before = (await admin.query("SELECT * FROM bop_media.product_image ORDER BY image_id"))
        .rows;
      await run(async (tx) => {
        await tx.query(
          "SELECT set_config('bop.brand_id',$1,true),set_config('bop.store_id','',true)",
          [brand],
        );
        await tx.query("UPDATE bop_media.product_image SET width=1", []).catch((error) => {
          if (error?.code !== "42501") throw error;
        });
        await tx.query("DELETE FROM bop_media.product_image", []).catch((error) => {
          if (error?.code !== "42501") throw error;
        });
      });
      assert.equal((await admin.query("UPDATE bop_media.product_image SET width=1")).rowCount, 0);
      assert.equal((await admin.query("DELETE FROM bop_media.product_image")).rowCount, 0);
      assert.deepEqual(
        (await admin.query("SELECT * FROM bop_media.product_image ORDER BY image_id")).rows,
        before,
      );

      // Constraints: exactly six renditions, pilot profile and Public classification only.
      const checkFails = async (overrides) => {
        const values = {
          renditions: JSON.stringify(record.renditions),
          profile: "PilotLocalFilesystemV1",
          classification: "Public",
          ...overrides,
        };
        await assert.rejects(
          admin.query(
            `INSERT INTO bop_media.product_image(image_id,tenant_id,brand_id,product_id,storage_profile,
               source_content_type,source_byte_size,width,height,renditions_json,data_classification,
               created_by_actor_id,created_at)
             VALUES($1,$2,$3,$4,$5,'image/jpeg',100,1280,960,$6::jsonb,$7,$8,'2026-10-17T12:00:00.000Z')`,
            [
              id(30),
              tenant,
              brand,
              product,
              values.profile,
              values.renditions,
              values.classification,
              actor,
            ],
          ),
          (error) => error?.code === "23514",
        );
      };
      await checkFails({ renditions: JSON.stringify(record.renditions.slice(0, 5)) });
      await checkFails({ renditions: "{}" });
      await checkFails({ profile: "S3" });
      await checkFails({ classification: "Internal" });
    } finally {
      await admin.end();
      await rm(join(directory, "..", ".."), { recursive: true, force: true });
    }
  });
});
